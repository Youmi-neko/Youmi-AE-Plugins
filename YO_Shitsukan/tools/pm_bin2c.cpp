// mac_port: tables/pm_<fn>.bin -> sk_pmath_tables.inc (C arrays; a build step on every platform, CMake runs it).
//   pm_bin2c <tables dir> <out.inc>
#include <cstdint>
#include <cstdio>
#include <string>
#include <vector>

int main(int argc, char** argv)
{
    if (argc < 3)
    {
        std::fprintf(stderr, "usage: pm_bin2c <tables dir> <out.inc>\n");
        return 2;
    }
    const char* names[8] = {"exp", "log", "sin", "cos", "pow22", "powig", "powthr", "powhalo"};
    FILE* fo = std::fopen(argv[2], "wb");
    if (!fo)
        return 1;
    std::fprintf(fo, "// generated by tools/pm_bin2c from tables/pm_*.bin - do not edit\n");
    for (const char* n : names)
    {
        const std::string p = std::string(argv[1]) + "/pm_" + n + ".bin";
        FILE* fi = std::fopen(p.c_str(), "rb");
        if (!fi)
        {
            std::fprintf(stderr, "pm_bin2c: cannot open %s\n", p.c_str());
            return 1;
        }
        std::vector<uint32_t> v;
        unsigned char b[4];
        while (std::fread(b, 1, 4, fi) == 4)
            v.push_back((uint32_t)b[0] | ((uint32_t)b[1] << 8) | ((uint32_t)b[2] << 16) | ((uint32_t)b[3] << 24));  // little endian file
        std::fclose(fi);
        if (v.size() % 2)
        {
            std::fprintf(stderr, "pm_bin2c: %s has an odd number of words\n", p.c_str());
            return 1;
        }
        std::fprintf(fo, "const unsigned kPmTabN_%s = %u;\nconst uint32_t kPmTab_%s[] = {", n, (unsigned)(v.size() / 2), n);
        if (v.empty())
            std::fprintf(fo, "0xFFFFFFFFu, 0u");
        for (size_t i = 0; i < v.size(); ++i)
            std::fprintf(fo, "%s0x%08Xu", i ? (i % 8 ? "," : ",\n") : "\n", v[i]);
        std::fprintf(fo, "};\n");
    }
    std::fclose(fo);
    return 0;
}
